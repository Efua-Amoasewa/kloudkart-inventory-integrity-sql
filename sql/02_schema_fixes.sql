-- 02_schema_fixes.sql
-- The constraints Kloud Kart's schema never had, added so that NEW writes cannot repeat
-- the faults in docs/data_findings.md.
--
-- Rule used throughout: where existing rows already break a rule, the constraint is added
-- NOT VALID. PostgreSQL then enforces it on every insert and update from now on, but does
-- not certify the old rows. Old faults are reported, not silently rewritten: the correct
-- value for a negative stock or a missing customer is not something this script can know.
--
-- Checked against race_test.py: it inserts products with no category, and its cleanup
-- deletes order_items -> orders -> inventory_log -> products in that order, so none of
-- these constraints blocks it.

BEGIN;

-- ------------------------------------------------------------------ F-01 negative stock
-- The safety net under place_order: even a future bug cannot sell below zero.
-- 14 products are already negative, hence NOT VALID.
ALTER TABLE products
    ADD CONSTRAINT products_stock_not_negative CHECK (stock_quantity >= 0) NOT VALID;

-- ------------------------------------------------------------------ relationships
-- Zero existing orphans: these can be fully validated.
ALTER TABLE order_items
    ADD CONSTRAINT order_items_product_fk
    FOREIGN KEY (product_id) REFERENCES products (product_id);

ALTER TABLE products
    ADD CONSTRAINT products_category_fk
    FOREIGN KEY (category_id) REFERENCES categories (category_id);

-- Existing orphans (F-08, F-09, F-12, F-14): enforced for new rows only.
ALTER TABLE order_items
    ADD CONSTRAINT order_items_order_fk
    FOREIGN KEY (order_id) REFERENCES orders (order_id) NOT VALID;

ALTER TABLE orders
    ADD CONSTRAINT orders_customer_fk
    FOREIGN KEY (customer_id) REFERENCES customers (customer_id) NOT VALID;

ALTER TABLE inventory_log
    ADD CONSTRAINT inventory_log_product_fk
    FOREIGN KEY (product_id) REFERENCES products (product_id) NOT VALID;

ALTER TABLE categories
    ADD CONSTRAINT categories_parent_fk
    FOREIGN KEY (parent_id) REFERENCES categories (category_id) NOT VALID;

-- ------------------------------------------------------------------ value ranges
-- No existing line has quantity <= 0 or a negative price, so these validate in full.
-- NULL prices (F-10) pass a CHECK; they are reported, not blocked retroactively.
ALTER TABLE order_items
    ADD CONSTRAINT order_items_quantity_positive CHECK (quantity > 0),
    ADD CONSTRAINT order_items_price_not_negative CHECK (unit_price >= 0);

-- F-07: new emails must arrive trimmed. 1,314 existing rows do not, hence NOT VALID.
ALTER TABLE customers
    ADD CONSTRAINT customers_email_trimmed CHECK (email = trim(email)) NOT VALID;

COMMIT;

-- ------------------------------------------------------------------ F-03 order status
-- One row per spelling ever seen, mapped to one meaning. Orders must use a spelling that
-- is in the map (foreign key), so a new spelling forces an explicit decision instead of
-- silently dropping out of the Monday report.
-- counts_as_spend is a business decision (ADR-004): money taken and not given back.
BEGIN;

CREATE TABLE order_status_map (
    raw_status       text PRIMARY KEY,
    canonical_status text    NOT NULL,
    counts_as_spend  boolean NOT NULL
);

INSERT INTO order_status_map (raw_status, canonical_status, counts_as_spend)
SELECT spelling,
       canonical,
       canonical IN ('completed', 'shipped')
FROM (
    SELECT DISTINCT
           status AS spelling,
           CASE lower(trim(status))
               WHEN 'complete' THEN 'completed'
               WHEN 'canceled' THEN 'cancelled'
               ELSE lower(trim(status))
           END AS canonical
    FROM orders
) AS spellings;

-- The spelling place_order writes must exist even if the extract never used it exactly.
INSERT INTO order_status_map (raw_status, canonical_status, counts_as_spend)
VALUES ('completed', 'completed', true)
ON CONFLICT (raw_status) DO NOTHING;

ALTER TABLE orders
    ADD CONSTRAINT orders_status_known_fk
    FOREIGN KEY (status) REFERENCES order_status_map (raw_status);

COMMIT;

-- ------------------------------------------------------------------ id generation
-- The extract's ids were assigned by the application. New rows written inside the
-- database (place_order, stock movements) need the database to assign them.
--
-- Orders start at 1,000,000, not at max(order_id) + 1: the 692 orphaned order lines (F-08)
-- reference order ids 900,101-999,862. Counting up from 659,385 would eventually hand a new
-- order an id that already has somebody else's lines attached.
BEGIN;

ALTER TABLE orders
    ALTER COLUMN order_id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000);

ALTER TABLE order_items
    ALTER COLUMN order_item_id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('order_items', 'order_item_id'),
              (SELECT max(order_item_id) FROM order_items));

ALTER TABLE inventory_log
    ALTER COLUMN log_id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('inventory_log', 'log_id'),
              (SELECT max(log_id) FROM inventory_log));

COMMIT;
